use std::{env, fs, path::PathBuf};

// All flash layout choices live here. Firmware has the same allocation in
// both variants; storage occupies the rest of the physical flash.
const FLASH_BASE: usize = 0x1000_0000;
const FIRMWARE_SIZE: usize = 3 * 1024 * 1024;
const ERASE_SIZE: usize = 4096;

fn main() {
    let test_otp = env::var_os("CARGO_FEATURE_INSECURE_TEST_OTP").is_some();
    let provision_otp = env::var_os("CARGO_FEATURE_OTP_PROVISIONING").is_some();
    assert!(
        !(test_otp && provision_otp),
        "insecure-test-otp and otp-provisioning are mutually exclusive"
    );
    if test_otp {
        println!(
            "cargo:warning=INSECURE TEST OTP: root keys are stored in plaintext flash; do not deploy this firmware"
        );
    }
    let flash_size = if env::var_os("CARGO_FEATURE_FLASH_16MB").is_some() {
        16 * 1024 * 1024
    } else {
        4 * 1024 * 1024
    };
    let storage_start = FIRMWARE_SIZE;
    let storage_size = flash_size - storage_start;
    assert!(storage_start.is_multiple_of(ERASE_SIZE));
    assert!(storage_size.is_multiple_of(ERASE_SIZE));
    assert!(storage_size >= 2 * ERASE_SIZE);

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by Cargo"));
    let memory = include_str!("memory.x.in")
        .replace("@FLASH_BASE@", &format!("{FLASH_BASE:#x}"))
        .replace("@FIRMWARE_SIZE@", &FIRMWARE_SIZE.to_string())
        .replace(
            "@STORAGE_ORIGIN@",
            &format!("{:#x}", FLASH_BASE + storage_start),
        )
        .replace("@STORAGE_SIZE@", &storage_size.to_string());
    fs::write(out_dir.join("memory.x"), memory).expect("failed to generate memory.x");
    fs::write(
        out_dir.join("flash_layout.rs"),
        format!(
            "// Generated by build.rs; do not edit.\n\
             pub const FLASH_SIZE: usize = {flash_size};\n\
             pub const STORAGE_START: u32 = {storage_start};\n\
             pub const STORAGE_SIZE: usize = {storage_size};\n"
        ),
    )
    .expect("failed to generate flash_layout.rs");
    println!("cargo:rustc-link-search={}", out_dir.display());
    println!("cargo:rerun-if-changed=memory.x.in");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_FLASH_16MB");
    println!("cargo:rustc-link-arg-bins=--nmagic");
    println!("cargo:rustc-link-arg-bins=-Tlink.x");
    println!("cargo:rustc-link-arg-bins=-Tdefmt.x");
    println!("cargo:rustc-link-arg-examples=--nmagic");
    println!("cargo:rustc-link-arg-examples=-Tlink.x");
    println!("cargo:rustc-link-arg-examples=-Tdefmt.x");
}
