use doohickey_crypto::ctap::sha256;
use subtle::ConstantTimeEq;
use zeroize::Zeroizing;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    AlreadyTaken,
    WrongCore,
    Unprovisioned,
    AlreadyProvisioned,
    IncompleteProvisioning,
    Corrupt,
    InvalidValue,
    NotSealed,
    ProvisioningDisabled,
    PermissionDenied,
    ReadFailed,
    WriteFailed,
    Storage,
}

/// Validated record and hard-lock state, without exporting unsealed key bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MasterStatus {
    Blank,
    Unsealed,
    Sealed,
}

/// SHA-256 fingerprint of the ROM's secp256k1 boot PUBLIC key, as generated by
/// picotool. The private firmware-signing key must remain off-device.
#[derive(Debug, PartialEq, Eq)]
pub struct BootKeyHash([u8; 32]);

impl BootKeyHash {
    pub fn from_bytes(bytes: [u8; 32]) -> Result<Self, Error> {
        validate_value(&bytes)?;
        Ok(Self(bytes))
    }
    pub fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }
}

pub(super) const MAGIC: &[u8; 8] = b"DOOHOTP1";
pub(super) const COMMIT: &[u8; 4] = b"done";
// An even number of ECC rows: guarded reads validate adjacent row pairs (E17).
pub(super) const RECORD_SIZE: usize = 76;
pub(super) type Record = Zeroizing<[u8; RECORD_SIZE]>;

pub(super) fn validate_value(value: &[u8; 32]) -> Result<(), Error> {
    if value.iter().all(|b| *b == 0) || value.iter().all(|b| *b == 0xff) {
        Err(Error::InvalidValue)
    } else {
        Ok(())
    }
}

pub(super) fn encode(value: &[u8; 32]) -> Result<Record, Error> {
    validate_value(value)?;
    let mut record = Zeroizing::new([0; RECORD_SIZE]);
    record[..8].copy_from_slice(MAGIC);
    record[8..40].copy_from_slice(value);
    let digest = sha256(&record[..40]);
    record[40..72].copy_from_slice(&digest);
    record[72..].copy_from_slice(COMMIT);
    Ok(record)
}

pub(super) fn decode(record: &[u8]) -> Result<Zeroizing<[u8; 32]>, Error> {
    if record.len() != RECORD_SIZE || &record[72..] != COMMIT {
        return Err(Error::IncompleteProvisioning);
    }
    if &record[..8] != MAGIC || !bool::from(sha256(&record[..40]).ct_eq(&record[40..72])) {
        return Err(Error::Corrupt);
    }
    let mut value = Zeroizing::new([0; 32]);
    value.copy_from_slice(&record[8..40]);
    validate_value(&value)?;
    Ok(value)
}
